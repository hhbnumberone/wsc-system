"""整机物理常数 —— 实时模拟器与历史种子数据的共同基准。

为什么单独一个模块：**同一台台车会被两个地方描述**。

* `can_bus/simulator.py` 在 2 秒采样下产出**实时**数据；
* `server/seed.py` 在 1 分钟粒度上回顾**30 天历史**。

如果这两处的泵送速率、压力包络各写一份，演示时就会出现
"历史每个循环 6 方、实时只有 2 方"这种一眼假的现象。这类数字和
`params.py` 里的参数定义是同一类东西 —— **只能有一个来源**，所以放这里。

`params.py` 管"每个参数叫什么、什么范围算异常"；
`machine.py` 管"这台机器本身是什么样"。
"""
